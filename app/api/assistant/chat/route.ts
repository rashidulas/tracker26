import { after, NextRequest, NextResponse } from 'next/server';
import { runChatTurn } from '@/lib/assistant/chat';
import { approvalSecret } from '@/lib/assistant/engine';
import { getAssistantModel } from '@/lib/assistant/model';
import { getAppTimeZone, todayInAppTimeZone } from '@/lib/dates';
import { prisma } from '@/lib/prisma';
import { APP_CURRENCY } from '@/lib/utils';

export const runtime = 'nodejs';
export const maxDuration = 60;

/**
 * Streams one assistant turn as an AI SDK UI message stream (for useChat) and
 * saves it to the conversation.
 *
 * Body: { id, message, proposalEdits? }
 *   id             conversation id (generated by the browser for a new chat)
 *   message        the browser's newest UI message; earlier ones are loaded
 *                  from the database (lib/assistant/chat.ts)
 *   proposalEdits  changes made on approval cards, by tool call id
 */
export async function POST(request: NextRequest) {
  const config = getAssistantModel();
  if (!config.ok) {
    console.error('Assistant config:', config.error);
    return NextResponse.json({ error: config.error }, { status: 500 });
  }

  let body: { id?: unknown; message?: unknown; proposalEdits?: unknown };
  try {
    body = await request.json();
  } catch {
    return NextResponse.json({ error: 'Request body must be JSON' }, { status: 400 });
  }

  try {
    const result = await runChatTurn({
      chatDb: prisma,
      conversationId: body.id,
      message: body.message,
      proposalEdits: body.proposalEdits,
      model: config.model,
      provider: config.provider,
      deps: {
        db: prisma,
        today: todayInAppTimeZone(),
        timeZone: getAppTimeZone(),
        currency: APP_CURRENCY,
      },
      approvalSecret: approvalSecret(),
      // Title generation finishes after the response has been sent.
      background: (work) => after(work),
    });
    if (!result.ok) {
      return NextResponse.json({ error: result.error }, { status: result.status });
    }
    return result.response;
  } catch (error) {
    console.error('Assistant chat error:', error);
    return NextResponse.json(
      { error: 'The assistant is unavailable right now. Please try again.' },
      { status: 500 }
    );
  }
}
